#!/usr/bin/env python3
"""Generate lib/data/quran_surah_revelation.dart from the bundled Tanzil
metadata (assets/quran/quran-data.js, CC BY 3.0) — the Meccan/Medinan type of
each of the 114 surahs, used by the mushaf index («مكية – آياتها 7»).

    python tool/gen_surah_revelation.py

Fails unless exactly 114 surahs are read and their ayah counts sum to 6236.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "assets/quran/quran-data.js"
OUT = ROOT / "lib/data/quran_surah_revelation.dart"

text = SRC.read_text(encoding="utf-8", errors="replace")
block = text[text.index("QuranData.Sura = ["):text.index("];", text.index("QuranData.Sura = ["))]
rows = re.findall(r"\[(\d+), (\d+), \d+, \d+, .*?'(Meccan|Medinan)'\]", block)
if len(rows) != 114 or sum(int(r[1]) for r in rows) != 6236:
    raise SystemExit(f"unexpected Tanzil Sura table: {len(rows)} rows")
flags = ", ".join("true" if r[2] == "Meccan" else "false" for r in rows)
OUT.write_text(
    "// GENERATED by tool/gen_surah_revelation.py from assets/quran/quran-data.js\n"
    "// (Tanzil.net metadata, CC BY 3.0) — do not edit by hand.\n\n"
    "/// `kSurahMeccan[n - 1]` is true when surah n is Meccan (Tanzil's `type`).\n"
    f"const List<bool> kSurahMeccan = [{flags}];\n",
    encoding="utf-8",
)
print(f"114 surahs ({sum(r[2] == 'Meccan' for r in rows)} Meccan) -> {OUT.relative_to(ROOT)}")
