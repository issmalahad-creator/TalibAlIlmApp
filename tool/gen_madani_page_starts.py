"""Generate lib/data/madani_page_starts.dart — the first ayah of each of the
604 pages of the King Fahd Complex Madani muṣḥaf **1421H edition** (QCF V2),
the edition the app draws (MushafDatabase V1.01).

Source: assets/mushaf/mushaf_layout.json.gz (extracted from MushafDatabase).
Cross-checked 2026-11-12 against quran.com's per-edition page lookup:
0/604 differences with mushaf=1 (QCF V2, 1421H) and mushaf=19 (V4, 1441H);
36 differences with Tanzil's QuranData.Page, which follows the **1405H**
edition (= quran.com mushaf=2). See docs/quran/reports/PAGE_BOUNDARY_AUDIT.md.

Run: python tool/gen_madani_page_starts.py
"""
import gzip
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
layout = json.load(gzip.open(ROOT / 'assets/mushaf/mushaf_layout.json.gz'))

starts = []
lasts = []
for p in sorted(layout['pages'], key=lambda p: p['page']):
    ayat = sorted({(w['s'], w['a']) for w in p['words'] if w.get('s') and w.get('a')}
                  | {(m['s'], m['a']) for m in p['marks']})
    starts.append(ayat[0])
    lasts.append(ayat[-1])

# Invariants — refuse to write a broken table.
assert len(starts) == 604, len(starts)
assert starts[0] == (1, 1) and lasts[-1] == (114, 6)
for i in range(1, 604):
    (ps, pa), (s, a) = lasts[i - 1], starts[i]
    assert (s == ps and a == pa + 1) or (s == ps + 1 and a == 1), f'gap before page {i + 1}: {lasts[i - 1]} -> {starts[i]}'

body = ',\n'.join('  (%d, %d)' % sa for sa in starts)
out = ROOT / 'lib/data/madani_page_starts.dart'
out.write_text(f'''// GENERATED by tool/gen_madani_page_starts.py — do not edit by hand.
//
// First ayah `(surah, ayah)` of each page (index 0 = page 1) of the King Fahd
// Complex Madani muṣḥaf, 1421H edition — the same edition the reader draws
// (MushafDatabase V1.01). Verified against quran.com's edition lookup: 0/604
// pages differ. Tanzil's `QuranData.Page` (assets/quran/quran-data.js) is the
// older 1405H edition and differs on 36 pages; it must not be used for page
// numbers. Audit: docs/quran/reports/PAGE_BOUNDARY_AUDIT.md.

/// Page `n` starts at `kMadaniPageStarts[n - 1]`.
const List<(int, int)> kMadaniPageStarts = [
{body},
];
''', encoding='utf-8')
print('wrote', out, len(starts), 'pages')
